test('reads the airport, runway ends and tower', () => {
    const apt = parseAptDat(sample);
    assert.equal(apt.icao, 'KTST');
    assert.equal(apt.name, 'Test Field');
    assert.equal(apt.elevationFt, 20);
    assert.deepEqual(apt.origin, { lat: 42, lon: -71 });
    assert.equal(apt.tower.heightFt, 200);
    assert.equal(apt.runways.length, 1);
    assert.deepEqual(apt.runways[0].ends.map(e => e.name), ['09', '27']);
    assert.equal(apt.runways[0].ends[0].displacedM, 100);
    assert.equal(apt.runways[0].widthM, 45);
});

test('pavement keeps its outer ring and holes, and lines keep their painted type', () => {
    const apt = parseAptDat(sample);
    assert.equal(apt.pavements.length, 1);
    assert.equal(apt.pavements[0].rings.length, 2);
    assert.ok(apt.pavements[0].rings.every(r => r.closed));
    assert.deepEqual(apt.pavements[0].rings[0].nodes[1].ctrl, { lat: 42.0015, lon: -70.9995 });
    assert.equal(apt.pavements[0].rings[0].nodes[1].line, 1);
    assert.equal(apt.pavements[0].rings[0].nodes[1].light, 102);
    assert.equal(apt.lines.length, 1);
    assert.equal(apt.lines[0].rings[0].closed, false);
    assert.equal(apt.lines[0].rings[0].nodes[0].line, 4);
});

test('gates, jetways, network and frequencies are read', () => {
    const apt = parseAptDat(sample);
    assert.equal(apt.gates[0].name, '12');
    assert.equal(apt.gates[0].sizeClass, 'E');
    assert.deepEqual(apt.gates[0].airlines, ['AAL', 'DAL']);
    assert.equal(apt.jetways[0].lengthM, 17.22);
    assert.equal(apt.taxiNodes.size, 4);
    assert.equal(apt.taxiEdges[0].runway, true);
    assert.deepEqual(apt.taxiEdges[0].activeZones, [{ kind: 'departure', runways: ['09', '27'] }]);
    assert.equal(apt.taxiEdges[2].oneway, true);
    assert.equal(apt.frequencies[0].mhz, 135);
    assert.deepEqual(apt.windsocks, [{ lat: 42.0003, lon: -71.0004, lit: true, name: 'Windsock 1' }]);
});

test('a curved segment passes through both ends and bends toward its control point', () => {
    const apt = parseAptDat(sample);
    const points = tessellate(apt.pavements[0].rings[0], 8);
    assert.equal(points.length, 8 + 8 + 1 + 1);
    assert.deepEqual([points[0].lat, points[0].lon], [42.001, -71.001]);
    const middle = points[8 + 4];     // Halfway along the node 2 to node 3 curve.
    assert.ok(middle.lon > -71.0000, 'the curve bulges east toward the control point');
    assert.ok(points.slice(8, 16).every(p => p.line === 1));
});

test('routes follow one-way edges and name the taxiways and runway crossings', () => {
    const apt = parseAptDat(sample);
    const out = findRoute(apt, 0, 3);
    assert.deepEqual(out.nodes, [0, 1, 2, 3]);
    assert.deepEqual(describeRoute(out.edges), { via: ['B', 'K'], crossings: ['09/27'] });
    assert.equal(findRoute(apt, 3, 2), null, 'K is one-way');
});

test('the local projection keeps distances in meters', () => {
    const p = makeProjection({ lat: 42, lon: -71 });
    const a = { lat: 42.01, lon: -71.01 }, b = { lat: 42.0, lon: -70.99 };
    const pa = p.toLocal(a.lat, a.lon), pb = p.toLocal(b.lat, b.lon);
    assert.ok(Math.abs(Math.hypot(pa.x - pb.x, pa.z - pb.z) - distanceM(a, b)) < 2);
    assert.ok(pa.z < 0, 'north is negative z');
});

test('taxiway labels skip runways and unnamed edges and keep one per stretch', () => {
    const apt = parseAptDat(sample);
    const labels = taxiwayLabels(apt, 10);
    assert.deepEqual(labels.map(l => l.name).sort(), ['B', 'K']);
    assert.ok(labels.every(l => l.heading >= 0 && l.heading < 360));
    assert.equal(taxiwayLabels(apt, 1e6).length, 2, 'one label per name when spacing is huge');
});

test('a taxi route follows the taxiways named, in order', () => {
    // A square of taxiways: from node 0 to node 2 the short way is via P, the long way via Q then R.
    const apt = parseAptDat(`1     20 0 0 KSQR Square
1201  42.000 -71.000 both 0 a
1201  42.010 -71.000 both 1 b
1201  42.010 -70.990 both 2 c
1201  42.000 -70.990 both 3 d
1202 0 1 twoway taxiway_C P
1202 1 2 twoway taxiway_C P
1202 0 3 twoway taxiway_C Q
1202 3 2 twoway taxiway_C R
`);
    assert.deepEqual(findRouteVia(apt, 0, 2, []).nodes, [0, 1, 2]);
    assert.deepEqual(findRouteVia(apt, 0, 2, ['Q', 'R']).nodes, [0, 3, 2]);
    assert.deepEqual(describeRoute(findRouteVia(apt, 0, 2, ['Q', 'R']).edges).via, ['Q', 'R']);
    assert.equal(findRouteVia(apt, 0, 2, ['R', 'Q']), null, 'R then Q does not reach c');
});
